import fs from 'node:fs'
import path from 'node:path'

// 生成 public/content/vault-notes 下目录的 index.md，只改用户可见中文名（frontmatter title），
// URL 与磁盘 slug 保持不变。Quartz 的 Explorer（读 contentIndex）、面包屑（读目录 index 的
// frontmatter title）与目录页（folder-page 插件）都以目录 index 的 title 作为显示名。

const DEFAULT_CONTENT = 'content'
const DEFAULT_MAPPING = 'folder-titles.json'
const MARKER = '<!-- folder-index: generated by scripts/build-folder-indexes.mjs -->'
const GENERATED_TAG = 'folder-index'

function parseArgs(argv) {
  const opts = { check: false, content: DEFAULT_CONTENT, mapping: DEFAULT_MAPPING }
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]
    if (arg === '--check') opts.check = true
    else if (arg === '--content') opts.content = argv[++i]
    else if (arg === '--mapping') opts.mapping = argv[++i]
    else throw new Error('未知参数: ' + arg)
  }
  return opts
}

function toPosix(p) { return p.split(path.sep).join('/') }

function walk(dir, base, found) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      if (entry.name === 'assets') continue
      walk(full, base, found)
    } else if (entry.name.endsWith('.md')) {
      found.add(toPosix(path.relative(base, dir)))
    }
  }
}

// 公开可见目录 = 直接或间接含有 .md 的目录，加上它们的全部祖先目录
function discoverVisibleDirs(contentRoot) {
  // 以 content 为基准，使路径带 vault-notes/ 前缀，与映射文件的键一致
  const base = toPosix(contentRoot)
  const withMarkdown = new Set()
  walk(path.join(contentRoot, 'vault-notes'), base, withMarkdown)
  const visible = new Set()
  for (const dir of withMarkdown) {
    const parts = dir.split('/')
    for (let i = 1; i <= parts.length; i++) visible.add(parts.slice(0, i).join('/'))
  }
  return visible
}

function readTitle(file) {
  const text = fs.readFileSync(file, 'utf8')
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!match) return null
  const line = match[1].split(/\r?\n/).find((l) => /^title\s*:/.test(l))
  if (!line) return null
  return line.replace(/^title\s*:\s*/, '').replace(/^["']|["']$/g, '').trim()
}

function listDirectNotes(contentRoot, dir) {
  const full = path.join(contentRoot, dir)
  return fs.readdirSync(full, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith('.md') && e.name !== 'index.md')
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b, 'zh-CN', { numeric: true }))
    .map((name) => {
      const file = path.join(full, name)
      const title = readTitle(file) || name.replace(/\.md$/, '')
      return { slug: dir + '/' + name.replace(/\.md$/, ''), title, name }
    })
}

function pickEntryNotes(notes) {
  const scored = notes.map((note) => {
    const base = note.name.toLowerCase()
    let score = 2
    if (/^00[-_.\s]/.test(base) || /^readme/.test(base)) score = 0
    else if (/guide|导读|knowledge-map|知识地图|index-map/.test(base)) score = 1
    return { note, score }
  })
  scored.sort((a, b) => a.score - b.score || a.note.name.localeCompare(b.note.name, 'zh-CN', { numeric: true }))
  return scored.slice(0, 4).map((item) => item.note)
}

function renderFolderIndex(contentRoot, dir, entry, mapping) {
  const notes = listDirectNotes(contentRoot, dir)
  const entries = pickEntryNotes(notes)
  const subdirs = Object.keys(mapping.folders)
    .filter((key) => key !== dir && key.startsWith(dir + '/') && key.slice(dir.length + 1).indexOf('/') === -1)
    .sort((a, b) => mapping.folders[a].title.localeCompare(mapping.folders[b].title, 'zh-CN'))
  const lines = []
  lines.push('---')
  lines.push('title: ' + entry.title)
  lines.push('description: ' + entry.description)
  lines.push('tags: []')
  lines.push('---')
  lines.push('')
  lines.push(MARKER)
  lines.push('')
  lines.push(entry.description)
  lines.push('')
  if (entries.length > 0) {
    lines.push('## 建议从这里开始')
    lines.push('')
    for (const note of entries) lines.push('- [[' + note.slug + '|' + note.title + ']]')
    lines.push('')
  }
  if (subdirs.length > 0) {
    lines.push('## 子目录')
    lines.push('')
    for (const sub of subdirs) lines.push('- [[' + sub + '/index|' + mapping.folders[sub].title + ']]')
    lines.push('')
  }
  lines.push('> [!note] 目录与来源')
  lines.push('> 本目录对应 Obsidian 源库中的「' + entry.source + '」。页面地址保持英文 slug：' + dir + '。')
  lines.push('> 显示名映射维护在 folder-titles.json，由 npm run folders:build 生成；请勿手工编辑本页。')
  lines.push('')
  return lines.join('\n')
}

function plannedWrites(opts) {
  const mapping = JSON.parse(fs.readFileSync(opts.mapping, 'utf8'))
  if (!mapping || typeof mapping.folders !== 'object') throw new Error('映射文件缺少 folders 对象')
  const contentRoot = opts.content
  const vaultRoot = 'vault-notes'
  const visible = discoverVisibleDirs(contentRoot)
  const mappingDirs = Object.keys(mapping.folders)
  const problems = []
  const writes = []
  const manualChecks = []
  for (const dir of visible) {
    if (!mapping.folders[dir]) problems.push('缺少目录映射: ' + dir)
  }
  for (const dir of mappingDirs) {
    const entry = mapping.folders[dir]
    if (!entry.title || !entry.source) problems.push('映射项缺少 title/source: ' + dir)
    if (!visible.has(dir)) problems.push('映射项在公开内容中不存在: ' + dir)
    const parent = dir.split('/').slice(0, -1).join('/')
    if (parent && !mapping.folders[parent]) problems.push('父目录未映射（面包屑会残留英文）: ' + dir)
    const indexFile = path.join(contentRoot, dir, 'index.md')
    if (entry.manual) {
      if (!fs.existsSync(indexFile)) { problems.push('人工入口页不存在: ' + dir + '/index.md'); continue }
      manualChecks.push({ dir, indexFile, expected: entry.title })
      continue
    }
    const desired = renderFolderIndex(contentRoot, dir, entry, mapping)
    if (!fs.existsSync(indexFile)) { writes.push({ dir, indexFile, desired, action: 'create' }); continue }
    const current = fs.readFileSync(indexFile, 'utf8').replace(/\r\n/g, '\n')
    if (!current.includes(MARKER)) { problems.push('拒绝覆盖人工维护的目录页: ' + dir + '/index.md（缺少生成标记）'); continue }
    writes.push({ dir, indexFile, desired, action: current === desired ? 'unchanged' : 'update' })
  }
  // 生成文件不能脱离映射继续存在
  for (const dir of visible) {
    const indexFile = path.join(contentRoot, dir, 'index.md')
    if (!fs.existsSync(indexFile)) continue
    const text = fs.readFileSync(indexFile, 'utf8')
    if (text.includes(MARKER) && !mapping.folders[dir]) problems.push('存在未登记映射的生成目录页: ' + dir)
  }
  return { mapping, visible, writes, problems, manualChecks }
}

function validateManual(checks, problems) {
  for (const check of checks) {
    const title = readTitle(check.indexFile)
    if (title !== check.expected) problems.push('人工入口页标题不符: ' + check.dir + '/index.md 期望「' + check.expected + '」实际「' + title + '」')
  }
}

function main() {
  const opts = parseArgs(process.argv.slice(2))
  const result = plannedWrites(opts)
  validateManual(result.manualChecks, result.problems)
  if (result.problems.length > 0) {
    console.error('目录本地化检查失败：')
    for (const problem of result.problems) console.error('  - ' + problem)
    process.exit(1)
  }
  const changes = result.writes.filter((w) => w.action !== 'unchanged')
  if (opts.check) {
    if (changes.length > 0) {
      console.error('目录 index 页过期，需要运行 npm run folders:build：')
      for (const change of changes) console.error('  - ' + change.action + ': ' + change.dir + '/index.md')
      process.exit(1)
    }
    console.log('目录本地化检查通过：' + result.visible.size + ' 个目录，' + result.writes.length + ' 个生成页均为最新')
    return
  }
  for (const change of changes) {
    fs.writeFileSync(change.indexFile, change.desired)
    console.log(change.action + ': ' + change.dir + '/index.md')
  }
  console.log('目录本地化完成：' + result.visible.size + ' 个目录，新增 ' + changes.filter((c) => c.action === 'create').length + '，更新 ' + changes.filter((c) => c.action === 'update').length + '，未变 ' + result.writes.filter((w) => w.action === 'unchanged').length)
}

main()